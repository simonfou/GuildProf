#!/usr/bin/env python3
"""Generate GuildProf/Data/Recipes.lua from wago.tools DB2 CSVs.

Usage: python3 -I tools/gen_recipes.py <csv_dir> <build> > GuildProf/Data/Recipes.lua

<csv_dir> holds SkillLine, SkillLineAbility, SpellEffect, SpellReagents
(https://wago.tools/db2/<Table>/csv?build=<build>). A recipe is a
SkillLineAbility row of a profession skill line whose spell has a
SpellReagents row.
"""
import csv
import sys

PROFESSIONS = [164, 165, 171, 182, 185, 186, 197, 202, 333, 129, 356, 393]
CREATE_ITEM = "24"


def rows(d, table):
    with open(f"{d}/{table}.csv", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def main():
    d, build = sys.argv[1], sys.argv[2]
    reagents = {r["SpellID"]: r for r in rows(d, "SpellReagents")}
    creates = {}
    for e in sorted(rows(d, "SpellEffect"), key=lambda e: int(e["EffectIndex"])):
        if e["Effect"] == CREATE_ITEM and e["SpellID"] not in creates and e["EffectItemType"] != "0":
            count = max(1, int(float(e["EffectBasePointsF"] or "1")))
            creates[e["SpellID"]] = (int(e["EffectItemType"]), count)
    wanted = {str(p) for p in PROFESSIONS}
    recipes = {}
    for r in rows(d, "SkillLineAbility"):
        spell = r["Spell"]
        if r["SkillLine"] not in wanted or spell not in reagents or spell in recipes:
            continue
        item, count = creates.get(spell, (0, 0))
        entry = [int(r["SkillLine"]), int(r["MinSkillLineRank"]), item, count]
        rg = reagents[spell]
        for i in range(8):
            rid = int(rg[f"Reagent_{i}"])
            n = int(rg[f"ReagentCount_{i}"])
            if rid > 0 and n > 0:
                entry += [rid, n]
        recipes[int(spell)] = entry

    out = sys.stdout
    out.write("local _, ns = ...\n\n")
    out.write(f"-- Generated by tools/gen_recipes.py from DB2 build {build}. Do not edit.\n")
    out.write("-- [recipeSpellID] = { skillLine, minSkill, itemID (0: no item), count,\n")
    out.write("--                     reagentItemID, reagentCount, ... }\n")
    out.write(f'ns.RecipeBuild = "{build}"\n')
    out.write("ns.Recipes = {\n")
    for spell in sorted(recipes):
        out.write(f"\t[{spell}] = {{ {', '.join(str(v) for v in recipes[spell])} }},\n")
    out.write("}\n")
    print(f"{len(recipes)} recipes", file=sys.stderr)


if __name__ == "__main__":
    main()
